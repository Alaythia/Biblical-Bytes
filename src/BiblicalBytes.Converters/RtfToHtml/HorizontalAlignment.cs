namespace BiblicalBytes.Converters.RtfToHtml;

/// <summary>
/// Defines the horizontal alignment options for elements within the RTF document.
/// </summary>
public enum HorizontalAlignment
{
    /// <summary>
    /// Aligns the element to the left.
    /// </summary>
    Left,

    /// <summary>
    /// Aligns the element to the right.
    /// </summary>
    Right,

    /// <summary>
    /// Centers the element.
    /// </summary>
    Center
}